"""
نقطه ورود اصلی برنامه (Main Entry Point) - Orchestrator
این ماژول مسئولیت‌های زیر را بر عهده دارد:
- پیکربندی سیستم لاگ‌گیری متمرکز برای کل برنامه
- مقداردهی اولیه دیتابیس و اتصال به منابع داده
- راه‌اندازی همزمان چهار کامپوننت اصلی:
    1. دیتابیس (Database)
    2. موتور اتوماسیون (Automation Engine) - در ترد پس‌زمینه
    3. کلاینت روبیکا (Rubpy Client) - در ترد جداگانه
    4. ربات تلگرام/روبیکا (Bot) - در ترد اصلی (Blocking)
- مدیریت سیگنال‌های سیستم برای توقف ایمن (Graceful Shutdown)
- مدیریت خطاهای سطح بالا و جلوگیری از کرش برنامه

معماری اجرایی:
┌─────────────────────────────────────┐
│           main() [Main Thread]       │
├─────────────────────────────────────┤
│  • init_db()                        │
│  • start_automation() → [AutoThread]│
│  • client.run()     → [RubpyClient] │
│  • bot.run()        → [Main Thread] │ ← حلقه اصلی برنامه
└─────────────────────────────────────┘
"""

import threading
import signal
import sys
import logging
import os
from dotenv import load_dotenv

from database import init_db
from automation import start_automation
from client import client
from bot import bot

# ============================================================
# ⚙️ پیکربندی لاگ‌گیری متمرکز (Centralized Logging Setup)
# ============================================================
load_dotenv()

# خواندن تنظیمات لاگ از متغیرهای محیطی با مقادیر پیش‌فرض
log_level = os.getenv("LOG_LEVEL", "INFO").upper()
log_file = os.getenv("LOG_FILE_PATH", "./logs/app.log")

# پیکربندی پایه سیستم لاگ‌گیری
logging.basicConfig(
    level=getattr(logging, log_level),
    format='%(asctime)s | %(name)-10s | %(levelname)-8s | %(message)s',
    handlers=[
        # خروجی به کنسول (برای مشاهده زنده)
        logging.StreamHandler(sys.stdout),
        # خروجی به فایل (برای ثبت تاریخچه و دیباگ)
        logging.FileHandler(log_file, encoding='utf-8', mode='a')
    ]
)

# ایجاد لاگر اختصاصی برای ماژول اصلی
log = logging.getLogger("MAIN")


# ============================================================
# 🛠️ توابع کمکی و مدیریت اجرا
# ============================================================
def run_client_safe() -> None:
    """
    اجرای ایمن کلاینت روبیکا در یک ترد جداگانه.

    این تابع کلاینت روبیکا را در یک ترد مجزا اجرا می‌کند تا از مسدود شدن
    حلقه اصلی ربات (bot.run) جلوگیری شود. تمام خطاهای رخ‌داده در سطح
    کلاینت ثبت می‌شوند تا برنامه اصلی کرش نکند.

    Raises:
        Exception: هر خطایی در اجرای کلاینت ثبت شده و swallow می‌شود.

    Note:
        این تابع به‌عنوان target برای threading.Thread استفاده می‌شود.
    """
    try:
        log.info("📡 راه‌اندازی کلاینت روبیکا...")
        # اجرای حلقه اصلی کلاینت (این متد blocking است)
        client.run()
    except Exception as e:
        log.error(f"❌ خطای کلاینت: {e}")


def graceful_shutdown(signum: int, frame) -> None:
    """
    هندلر سیگنال برای توقف ایمن و تمیز برنامه.

    این تابع زمانی فراخوانی می‌شود که کاربر با Ctrl+C (SIGINT) یا سیستم
    با SIGترم (SIGTERM) درخواست توقف برنامه را بدهد. در حال حاضر با
    خروج از برنامه، تردهای Daemon به‌صورت خودکار متوقف می‌شوند.

    Args:
        signum (int): شماره سیگنال دریافتی (مثلاً 2 برای SIGINT).
        frame: فریم پشته در لحظه دریافت سیگنال.

    Note:
        در نسخه‌های پیشرفته‌تر می‌توان اینجا منطق cleanup مثل بستن
        اتصال دیتابیس یا ذخیره وضعیت را اضافه کرد.
    """
    log.info("🛑 دریافت سیگنال توقف. در حال خروج ایمن...")
    sys.exit(0)


# ============================================================
# 🚀 تابع اصلی برنامه (Application Entrypoint)
# ============================================================
def main() -> None:
    """
    تابع اصلی برنامه - هماهنگ‌کننده راه‌اندازی تمام کامپوننت‌ها.

    این تابع مراحل زیر را به ترتیب اجرا می‌کند:
    1. ثبت هندلرهای سیگنال برای مدیریت توقف ایمن
    2. مقداردهی اولیه دیتابیس و جداول
    3. راه‌اندازی موتور اتوماسیون در پس‌زمینه (Non-blocking)
    4. راه‌اندازی کلاینت روبیکا در ترد جداگانه (Non-blocking)
    5. راه‌اندازی ربات در ترد اصلی (Blocking - حلقه اصلی برنامه)

    Flow Execution:
        ┌─[1] init_db()
        │
        ├─[2] start_automation() ──▶ [AutoThread: Daemon]
        │
        ├─[3] client.run() ─────────▶ [RubpyClient: Daemon]
        │
        └─[4] bot.run() ────────────▶ [Main Thread: Blocking] ← برنامه اینجا می‌ماند

    Note:
        - تردهای اتوماسیون و کلاینت به صورت Daemon تنظیم شده‌اند، یعنی
          با پایان ترد اصلی (ربات)، این ترد‌ها نیز متوقف می‌شوند.
        - bot.run() یک متد blocking است و تا زمانی که ربات متوقف نشود،
          اجرای برنامه ادامه می‌یابد.
    """
    # ثبت هندلرهای سیگنال برای مدیریت graceful shutdown
    signal.signal(signal.SIGINT, graceful_shutdown)
    signal.signal(signal.SIGTERM, graceful_shutdown)

    log.info("🚀 شروع راه‌اندازی یکپارچه ربات و اتوماسیون...")

    # ─────────────────────────────────────────────────────
    # [1] مقداردهی اولیه دیتابیس
    # ─────────────────────────────────────────────────────
    init_db()
    log.info("✅ دیتابیس آماده است.")

    # ─────────────────────────────────────────────────────
    # [2] راه‌اندازی موتور اتوماسیون (پس‌زمینه)
    # ─────────────────────────────────────────────────────
    start_automation()
    log.info("✅ موتور اتوماسیون در پس‌زمینه فعال شد.")

    # ─────────────────────────────────────────────────────
    # [3] راه‌اندازی کلاینت روبیکا (ترد جداگانه)
    # ─────────────────────────────────────────────────────
    client_thread = threading.Thread(
        target=run_client_safe,
        daemon=True,  # Daemon: با پایان برنامه اصلی، این ترد هم کشته می‌شود
        name="RubpyClient"
    )
    client_thread.start()
    log.info("✅ کلاینت روبیکا در ترد جداگانه راه‌اندازی شد.")

    # ─────────────────────────────────────────────────────
    # [4] راه‌اندازی ربات (ترد اصلی - حلقه Blocking)
    # ─────────────────────────────────────────────────────
    log.info("👑 راه‌اندازی بات...")
    try:
        # این متد blocking است و تا توقف ربات اجرا می‌ماند
        bot.run()
    except KeyboardInterrupt:
        # مدیریت توقف دستی توسط کاربر (Ctrl+C)
        log.info("⏹️ توقف دستی توسط کاربر.")
    except Exception as e:
        # مدیریت خطاهای غیرمنتظره در سطح ربات
        log.error(f"💥 خطای بات: {e}")
        # در صورت نیاز می‌توان اینجا cleanup اضافی انجام داد


# ============================================================
# 🎯 نقطه شروع اجرا (Script Entry Point)
# ============================================================
if __name__ == "__main__":
    """
    نقطه ورود اجرای اسکریپت.

    این بلوک اطمینان حاصل می‌کند که تابع main() فقط زمانی اجرا شود
    که فایل به صورت مستقیم (python main.py) اجرا شده باشد، نه وقتی
    که از ماژول دیگری import شده باشد.
    """
    main()